// Package clientproc 负责关闭正在运行的客户端进程。
//
// 它存在的唯一理由是「重启客户端」这个动作：改完压缩阈值之类的设置后，
// 客户端必须重新启动才读得到新值，而让用户自己去托盘退出、再回来点启动
// 太绕。有了它，界面上一个按钮就够了。
//
// 与 internal/migrate 里那个 IsRunning 的分工：
//   - IsRunning 只做探测，用于"搬运前警告客户端还开着"；
//   - 本包做终止，且**先温和后强制**——客户端是 Electron，
//     强杀会丢未落盘的会话。
package clientproc
